// Generates dist/tokens.css (runtime CSS variables, light + dark + motion modes)
// and dist/theme.css (Tailwind v4 @theme that points at those variables) from
// src/tokens.json. `--check` only validates tokens.json and writes nothing.
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'

const t = JSON.parse(readFileSync(new URL('./src/tokens.json', import.meta.url), 'utf8'))
const HEADER = '/* Generated by packages/tokens/build.mjs from src/tokens.json — do not edit by hand. */'

// ---------------------------------------------------------------- validation
const errors = []
const keys = (o) => Object.keys(o).filter((k) => !k.startsWith('$'))
const sameKeys = (a, b, what) => {
  const missing = a.filter((k) => !b.includes(k)).concat(b.filter((k) => !a.includes(k)))
  if (missing.length) errors.push(`${what} mismatch: ${missing.join(', ')}`)
}

const light = keys(t.color.light)
const dark = keys(t.color.dark)
sameKeys(light, dark, 'Light/dark token')
const COLOR = /^(#[0-9a-f]{6}|rgba\(\d{1,3}, \d{1,3}, \d{1,3}, (0|1|0?\.\d+)\))$/i
for (const mode of ['light', 'dark']) {
  for (const [k, v] of Object.entries(t.color[mode])) if (!COLOR.test(v)) errors.push(`color.${mode}.${k} is not #rrggbb or rgba(): ${v}`)
}
// Tailwind colour names drop the group (brand/accent → accent), so they must stay unique.
const twColor = (key) => key.split('/').pop()
const twNames = light.map(twColor)
const dupes = twNames.filter((n, i) => twNames.indexOf(n) !== i)
if (dupes.length) errors.push(`Colour names collide once the group is dropped: ${dupes.join(', ')}`)

for (const [k, s] of Object.entries(t.font.style)) {
  if (!t.font.family[s.family]) errors.push(`font.style.${k} uses unknown family ${s.family}`)
  for (const f of ['weight', 'size', 'lineHeight']) if (typeof s[f] !== 'number') errors.push(`font.style.${k}.${f} is not a number`)
}

const m = t.motion
const durationKeys = keys(m.duration)
sameKeys(durationKeys, keys(m.lite), 'motion.duration/motion.lite')
sameKeys(durationKeys, keys(m.reduce), 'motion.duration/motion.reduce')
for (const [k, v] of Object.entries(m.reduce)) {
  if (v > 100) errors.push(`motion.reduce.${k} is ${v} ms; reduced motion allows 100 ms at most`)
}
for (const [k, v] of Object.entries(m.lite)) {
  if (v > m.duration[k]) errors.push(`motion.lite.${k} (${v}) is longer than motion.duration.${k} (${m.duration[k]})`)
}
for (const [k, v] of Object.entries(m.easing)) {
  if (!/^cubic-bezier\(([-\d.]+,\s*){3}[-\d.]+\)$/.test(v)) errors.push(`motion.easing.${k} is not a cubic-bezier(): ${v}`)
}
const bps = Object.values(t.breakpoint)
if (bps.some((v, i) => i > 0 && v <= bps[i - 1])) errors.push('breakpoints must ascend')

if (errors.length) {
  console.error(errors.join('\n'))
  process.exit(1)
}
if (process.argv.includes('--check')) {
  console.log(
    `tokens ok: ${light.length} colors, ${Object.keys(t.font.style).length} text styles, ` +
      `${durationKeys.length} durations, ${bps.length} breakpoints`,
  )
  process.exit(0)
}

// ---------------------------------------------------------------- helpers
const varName = (key) => `--${key.replace(/\//g, '-')}`
const rem = (px) => `${+(px / 16).toFixed(4)}rem`
const ratio = (a, b) => +(a / b).toFixed(4)
const indent = (s, n = 2) => s.replace(/^(?=.)/gm, ' '.repeat(n))
const colors = (mode) => Object.entries(t.color[mode]).map(([k, v]) => `${varName(k)}: ${v};`).join('\n')
const durations = (set) => Object.entries(set).filter(([k]) => !k.startsWith('$')).map(([k, v]) => `--duration-${k}: ${v}ms;`).join('\n')
const tracking = (s) => (s.letterSpacing ? `${ratio(s.letterSpacing, s.size)}em` : null)
const isNumber = (s) => s.family === 'number'

// ---------------------------------------------------------------- tokens.css
// Runtime variables. `[data-theme]` works on <html> and on any subtree, so a
// gallery or a preview can force one theme inside a page of the other.
const tokensCss = [
  HEADER,
  ':root,',
  '[data-theme="light"] {',
  indent(colors('light')),
  '  color-scheme: light;',
  '}',
  ':root {',
  ...Object.entries(t.font.family).map(([k, v]) => `  --font-${k}: ${v};`),
  // Full text style as a `font` shorthand (for canvas share cards and plain CSS).
  // Tailwind's own --text-* namespace (font-size) lives in theme.css.
  ...Object.entries(t.font.style).flatMap(([k, s]) => [
    `  --type-${k}: ${s.weight} ${rem(s.size)}/${ratio(s.lineHeight, s.size)} var(--font-${s.family});`,
    ...(tracking(s) ? [`  --type-${k}-tracking: ${tracking(s)};`] : []),
  ]),
  ...Object.entries(t.radius).map(([k, v]) => `  --radius-${k}: ${v}px;`),
  ...Object.entries(t.space).map(([k, v]) => `  --space-${k}: ${v}px;`),
  ...Object.entries(t.size).map(([k, v]) => `  --size-${k}: ${v}px;`),
  ...Object.entries(t.breakpoint).map(([k, v]) => `  --bp-${k}: ${v}px;`),
  indent(durations(m.duration)),
  ...Object.entries(m.easing).map(([k, v]) => `  --ease-${k}: ${v};`),
  '}',
  '@media (prefers-color-scheme: dark) {',
  '  :root:not([data-theme="light"]) {',
  indent(colors('dark'), 4),
  '    color-scheme: dark;',
  '  }',
  '}',
  ':root[data-theme="dark"],',
  '[data-theme="dark"] {',
  indent(colors('dark')),
  '  color-scheme: dark;',
  '}',
  '/* Motion modes. data-motion is set before paint by the layout script. */',
  'html[data-motion="lite"] {',
  indent(durations(m.lite)),
  '}',
  'html[data-motion="reduce"] {',
  indent(durations(m.reduce)),
  '}',
  '@media (prefers-reduced-motion: reduce) {',
  '  html:not([data-motion="full"]) {',
  indent(durations(m.reduce), 4),
  '  }',
  '}',
  '',
].join('\n')

// ---------------------------------------------------------------- theme.css
// Tailwind v4 theme. Import after `@import "tailwindcss"` and tokens.css.
// Colours are `inline` so utilities read the runtime variables directly and
// light/dark (and subtree [data-theme]) switch with no `dark:` variant.
const textStyles = Object.entries(t.font.style).flatMap(([k, s]) => [
  `--text-${k}: ${rem(s.size)};`,
  `--text-${k}--line-height: ${ratio(s.lineHeight, s.size)};`,
  `--text-${k}--font-weight: ${s.weight};`,
  ...(tracking(s) ? [`--text-${k}--letter-spacing: ${tracking(s)};`] : []),
])
const typeUtilities = Object.entries(t.font.style).map(([k, s]) =>
  [
    `@utility type-${k} {`,
    `  font-family: var(--font-${s.family});`,
    `  font-size: ${rem(s.size)};`,
    `  line-height: ${ratio(s.lineHeight, s.size)};`,
    `  font-weight: ${s.weight};`,
    ...(tracking(s) ? [`  letter-spacing: ${tracking(s)};`] : []),
    ...(isNumber(s) ? ['  font-variant-numeric: tabular-nums;'] : []),
    '}',
  ].join('\n'),
)

const themeCss = [
  HEADER,
  '/* Use after: @import "tailwindcss"; @import "@hisab/tokens/tokens.css"; */',
  '',
  '/* dark: matches [data-theme=dark] anywhere above, or the system setting unless [data-theme=light] is set. */',
  '@custom-variant dark {',
  '  &:where([data-theme="dark"], [data-theme="dark"] *) {',
  '    @slot;',
  '  }',
  '  @media (prefers-color-scheme: dark) {',
  '    &:where(:not([data-theme="light"], [data-theme="light"] *)) {',
  '      @slot;',
  '    }',
  '  }',
  '}',
  '',
  '@theme inline {',
  '  --color-*: initial;',
  ...light.map((k) => `  --color-${twColor(k)}: var(${varName(k)});`),
  '}',
  '',
  '@theme {',
  '  --font-*: initial;',
  ...Object.entries(t.font.family).map(([k, v]) => `  --font-${k}: ${v};`),
  `  --font-sans: ${t.font.family.body};`,
  `  --font-mono: ${t.font.family.number};`,
  '',
  '  --text-*: initial;',
  indent(textStyles.join('\n')),
  '',
  '  --radius-*: initial;',
  ...Object.entries(t.radius).map(([k, v]) => `  --radius-${k}: ${v}px;`),
  '',
  `  --spacing: ${rem(t.space['1'])};`,
  `  --spacing-touch: ${t.size.touch}px;`,
  `  --spacing-bottom-nav: ${t.size['bottom-nav']}px;`,
  '',
  `  --container-content: ${t.size['content-max']}px;`,
  `  --container-dialog: ${t.size['dialog-max']}px;`,
  `  --container-form: ${t.size['form-max']}px;`,
  `  --container-frame-mobile: ${t.size['frame-mobile']}px;`,
  '',
  '  --breakpoint-*: initial;',
  ...Object.entries(t.breakpoint).map(([k, v]) => `  --breakpoint-${k}: ${v}px;`),
  '',
  '  --ease-*: initial;',
  ...Object.entries(m.easing).map(([k, v]) => `  --ease-${k}: ${v};`),
  '  --default-transition-duration: var(--duration-hover);',
  `  --default-transition-timing-function: ${m.easing.out};`,
  '}',
  '',
  '/* duration-press … duration-sheet. They change with html[data-motion], so utilities read tokens.css at runtime. */',
  '@theme inline {',
  ...durationKeys.map((k) => `  --transition-duration-${k}: var(--duration-${k});`),
  '}',
  '',
  '/* One class per Figma text style: family, size, line height, weight and tracking. */',
  ...typeUtilities,
  '',
].join('\n')

// Write only when the content changed, so running dev servers (one per port) are not
// sent a needless CSS reload each time another one starts and rebuilds the tokens.
mkdirSync(new URL('./dist/', import.meta.url), { recursive: true })
const written = []
for (const [name, css] of [['tokens.css', tokensCss], ['theme.css', themeCss]]) {
  const file = new URL(`./dist/${name}`, import.meta.url)
  if (existsSync(file) && readFileSync(file, 'utf8') === css) continue
  writeFileSync(file, css)
  written.push(`dist/${name}`)
}
console.log(written.length ? `wrote ${written.join(' and ')}` : 'dist/tokens.css and dist/theme.css are up to date')
