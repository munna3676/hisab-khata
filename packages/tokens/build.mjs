// Generates dist/tokens.css from src/tokens.json. `--check` only validates.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'

const t = JSON.parse(readFileSync(new URL('./src/tokens.json', import.meta.url), 'utf8'))
const varName = (key) => `--${key.replace(/\//g, '-')}`

const light = Object.keys(t.color.light)
const dark = Object.keys(t.color.dark)
const missing = light.filter((k) => !dark.includes(k)).concat(dark.filter((k) => !light.includes(k)))
if (missing.length) {
  console.error(`Light/dark token mismatch: ${missing.join(', ')}`)
  process.exit(1)
}
if (process.argv.includes('--check')) {
  console.log(`tokens ok: ${light.length} colors, ${Object.keys(t.font.style).length} text styles`)
  process.exit(0)
}

const colors = (mode) => Object.entries(t.color[mode]).map(([k, v]) => `  ${varName(k)}: ${v};`).join('\n')
const lines = [
  '/* Generated by packages/tokens/build.mjs — do not edit by hand. */',
  ':root {',
  colors('light'),
  ...Object.entries(t.font.family).map(([k, v]) => `  --font-${k}: ${v};`),
  ...Object.entries(t.font.style).flatMap(([k, s]) => [
    `  --text-${k}: ${s.weight} ${s.size / 16}rem/${+(s.lineHeight / s.size).toFixed(4)} var(--font-${s.family});`,
    ...(s.letterSpacing ? [`  --text-${k}-tracking: ${+(s.letterSpacing / s.size).toFixed(4)}em;`] : []),
  ]),
  ...Object.entries(t.radius).map(([k, v]) => `  --radius-${k}: ${v}px;`),
  ...Object.entries(t.space).map(([k, v]) => `  --space-${k}: ${v}px;`),
  ...Object.entries(t.size).map(([k, v]) => `  --size-${k}: ${v}px;`),
  '  color-scheme: light;',
  '}',
  '@media (prefers-color-scheme: dark) {',
  '  :root:not([data-theme="light"]) {',
  colors('dark').replace(/^/gm, '  '),
  '    color-scheme: dark;',
  '  }',
  '}',
  ':root[data-theme="dark"] {',
  colors('dark'),
  '  color-scheme: dark;',
  '}',
  '',
]
mkdirSync(new URL('./dist/', import.meta.url), { recursive: true })
writeFileSync(new URL('./dist/tokens.css', import.meta.url), lines.join('\n'))
console.log('wrote dist/tokens.css')
