// Compiles every data/_schema/*.schema.json with ajv (JSON Schema 2020-12 +
// ajv-formats) into standalone ESM code in packages/data/src/generated/, so the
// app validates downloaded data without eval or new Function at runtime.
// The output is committed. Usage:
//   node scripts/build-validators.mjs           write packages/data/src/generated/
//   node scripts/build-validators.mjs --check   exit 1 if the committed output is stale
import { mkdirSync, readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs'
import { createRequire } from 'node:module'

// ajv lives in packages/data's dependencies, not at the repo root.
const require = createRequire(new URL('../packages/data/package.json', import.meta.url))
const { Ajv2020 } = require('ajv/dist/2020.js')
const standaloneCode = require('ajv/dist/standalone').default

const schemaDir = new URL('../data/_schema/', import.meta.url)
const outDir = new URL('../packages/data/src/generated/', import.meta.url)
const check = process.argv.includes('--check')

/** 'mfs-charges' → 'mfsCharges' (an export name). */
const camel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())

const names = readdirSync(schemaDir)
  .filter((f) => f.endsWith('.schema.json'))
  .map((f) => f.slice(0, -'.schema.json'.length))
  .sort()

const ajv = new Ajv2020({ allErrors: true, strict: true, code: { source: true, esm: true, } })
// A RegExp format is inlined into the generated code (ajv-formats' uri would be a
// require()). Data sources are web pages, so only http(s) URLs pass.
ajv.addFormat('uri', /^https?:\/\/[^\s/$.?#][^\s]*$/i)
const exportsById = {}
for (const name of names) {
  const schema = JSON.parse(readFileSync(new URL(`${name}.schema.json`, schemaDir), 'utf8'))
  if (schema.$id !== `https://hisabkhata.app/schema/${name}.json`) {
    throw new Error(`${name}.schema.json: $id must be https://hisabkhata.app/schema/${name}.json`)
  }
  ajv.addSchema(schema)
  // common.schema.json only holds $defs; it is compiled through the files that use it.
  if (name !== 'common') exportsById[camel(name)] = schema.$id
}

const header = '// Generated by scripts/build-validators.mjs from data/_schema. Do not edit.\n/* eslint-disable */\n'
let js = header + standaloneCode(ajv, exportsById)
const entries = Object.keys(exportsById).map((exp) => {
  const name = exportsById[exp].slice('https://hisabkhata.app/schema/'.length, -'.json'.length)
  return [name, exp]
})
js += `\n\n/** Validators by schema name (the file name in data/_schema without .schema.json). */\nexport const validators = {\n${entries
  .map(([name, exp]) => `  ${JSON.stringify(name)}: ${exp},`)
  .join('\n')}\n}\n`
// ajv's ESM output still require()s two runtime helpers; inline them so the
// module is pure ESM with no dependency on ajv at runtime.
const RUNTIME = {
  'require("ajv/dist/runtime/ucs2length").default': `function ucs2length(str) {
  let length = 0
  for (let pos = 0; pos < str.length; length++) {
    const code = str.charCodeAt(pos++)
    if (code >= 0xd800 && code <= 0xdbff && pos < str.length && (str.charCodeAt(pos) & 0xfc00) === 0xdc00) pos++
  }
  return length
}`,
  'require("ajv/dist/runtime/equal").default': `function equal(a, b) {
  if (a === b) return true
  if (!a || !b || typeof a !== 'object' || typeof b !== 'object') return a !== a && b !== b
  if (Array.isArray(a) !== Array.isArray(b)) return false
  const ka = Object.keys(a)
  if (ka.length !== Object.keys(b).length) return false
  return ka.every((k) => Object.prototype.hasOwnProperty.call(b, k) && equal(a[k], b[k]))
}`,
}
for (const [call, fn] of Object.entries(RUNTIME)) js = js.split(call).join(`(${fn})`)
if (/\brequire\(/.test(js)) throw new Error('standalone code still uses require(); it must be pure ESM')

const dts =
  header +
  `import type { ErrorObject } from 'ajv'

/** A compiled schema check: true when data is valid; errors explain why not. */
export interface ValidateFunction {
  (data: unknown): boolean
  errors?: ErrorObject[] | null
}

${Object.keys(exportsById)
  .map((exp) => `export declare const ${exp}: ValidateFunction`)
  .join('\n')}

/** Validators by schema name (the file name in data/_schema without .schema.json). */
export declare const validators: Readonly<Record<${entries.map(([n]) => JSON.stringify(n)).join(' | ')}, ValidateFunction>>
`

const files = { 'validators.js': js, 'validators.d.ts': dts }
if (check) {
  const stale = Object.entries(files).filter(([f, text]) => {
    const path = new URL(f, outDir)
    return !existsSync(path) || readFileSync(path, 'utf8') !== text
  })
  for (const [f] of stale) console.error(`STALE  packages/data/src/generated/${f}: run node scripts/build-validators.mjs`)
  if (stale.length === 0) console.log(`${names.length} schemas, generated validators are up to date`)
  process.exit(stale.length ? 1 : 0)
}
mkdirSync(outDir, { recursive: true })
for (const [f, text] of Object.entries(files)) writeFileSync(new URL(f, outDir), text)
console.log(`${names.length} schemas → packages/data/src/generated/validators.js`)
